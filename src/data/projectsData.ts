/**
 * جدول کنترل و صحت‌سنجی معاونت‌ها دقیقاً بر اساس اکسل
 */
export function getDepartmentControlData() {
  const map = new Map<string, { total: number; stopped: number; running: number; withObstacle: number }>();
  
  for (const item of rawProjectsData) {
    const dep = item.depName;
    if (!map.has(dep)) {
      map.set(dep, { total: 0, stopped: 0, running: 0, withObstacle: 0 });
    }
    const current = map.get(dep)!;
    current.total += 1;
    if (item.status === 'متوقف') current.stopped += 1;
    else current.running += 1;
    if (item.obstacleNature !== 'ندارد') current.withObstacle += 1;
  }

  return Array.from(map.entries()).map(([depName, stats]) => ({
    departmentName: depName,
    rowCount: stats.total,
    stoppedCount: stats.stopped,
    inProgressCount: stats.running,
    withObstacleCount: stats.withObstacle
  }));
}
